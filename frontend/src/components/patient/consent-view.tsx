"use client";

import { useState } from "react";
import { useRouter } from "next/navigation";

import { Button } from "@/components/ui/button";
import { Card, CardContent, CardHeader, CardTitle } from "@/components/ui/card";
import { Checkbox } from "@/components/ui/checkbox";
import { Label } from "@/components/ui/label";
import { useConsentStatus } from "@/lib/auth/require-role";

/**
 * Plain-language consent, before any invite code. Nothing is recorded on this screen: it exists so
 * a person knows what the app does with their voice and who can read it. On the backend, consent
 * is granted by redeeming an invite, so this step ends by moving to /link.
 */
export function ConsentView() {
  const router = useRouter();
  const consent = useConsentStatus();
  const [agreed, setAgreed] = useState(false);
  const [error, setError] = useState<string | null>(null);

  if (consent.status === "ready" && consent.hasConsent) {
    return (
      <Card>
        <CardHeader>
          <CardTitle>You are already sharing with your care team</CardTitle>
        </CardHeader>
        <CardContent className="space-y-4">
          <p className="text-sm text-muted-foreground">
            {consent.clinicianName
              ? `${consent.clinicianName} can read the check-ins you submit from now on.`
              : "A clinician on your care team can read the check-ins you submit from now on."}
          </p>
          <p className="text-sm text-muted-foreground">
            You can stop that any time. Your care team sees only what you choose to share.
          </p>
        </CardContent>
      </Card>
    );
  }

  return (
    <div className="space-y-4">
      <Card>
        <CardHeader>
          <CardTitle>Before your first check-in</CardTitle>
        </CardHeader>
        <CardContent className="space-y-4 text-sm">
          <section className="space-y-1">
            <h2 className="font-medium">What we record</h2>
            <p className="text-muted-foreground">
              When you press record, your voice is turned into text. You read that text, and you can
              change it or delete any part of it before you submit. Only what you approve is kept.
            </p>
          </section>

          <section className="space-y-1">
            <h2 className="font-medium">Who sees it</h2>
            <p className="text-muted-foreground">
              Nobody until you choose otherwise. When you enter an invite code from your
              psychologist or psychiatrist, they can read the check-ins you submit after that
              moment. You can stop that at any time in Settings, and it hides your earlier
              check-ins from them too.
            </p>
          </section>

          <section className="space-y-1">
            <h2 className="font-medium">Where it goes</h2>
            <p className="text-muted-foreground">
              Your audio is sent to AssemblyAI, a speech-to-text service, and is not stored by
              Psylink. The text you approve is sent to our analysis service, which writes a short
              summary and suggests how you might be feeling. That summary is generated by a
              machine — it describes what you said, it is not a diagnosis, and it does not replace
              your care team.
            </p>
          </section>

          <section className="space-y-1">
            <h2 className="font-medium">What it is not</h2>
            <p className="text-muted-foreground">
              Psylink is not emergency care and cannot call for help. If you are in danger or might
              hurt yourself, contact your local emergency services, or use the “Need help now?”
              link at the top of every screen.
            </p>
          </section>

          <div className="flex items-start gap-3 rounded-lg border border-border bg-muted p-3">
            <Checkbox
              id="agree"
              checked={agreed}
              onCheckedChange={(checked) => {
                setAgreed(checked === true);
                setError(null);
              }}
              className="mt-0.5"
            />
            <Label htmlFor="agree" className="flex-1 cursor-pointer text-sm font-normal">
              I understand what is recorded, who can read it, and that Psylink is not emergency
              care.
            </Label>
          </div>

          {error ? (
            <p role="alert" className="text-sm text-destructive">
              {error}
            </p>
          ) : null}

          <Button
            size="lg"
            className="w-full"
            disabled={!agreed || consent.status === "loading"}
            onClick={() => {
              if (!agreed) {
                setError("Tick the box above to continue.");
                return;
              }
              router.push("/link");
            }}
          >
            Continue
          </Button>
        </CardContent>
      </Card>

      {consent.status === "error" ? (
        <p className="text-sm text-muted-foreground">
          We could not check whether you are already linked. You can continue, and this page will
          update when it loads.
        </p>
      ) : null}
    </div>
  );
}
