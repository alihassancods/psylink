"""Safety evaluation for the check-in pipeline.

    uv run python scripts/eval_safety.py                    # deterministic screen only, offline
    uv run python scripts/eval_safety.py --llm              # full pipeline (needs a key, costs)
    uv run python scripts/eval_safety.py --write docs/eval-results.md

Two different claims are measured, because they carry different risks:

**The keyword floor** is a binary detector of *high* risk and it runs offline, so these numbers
are reproducible on any machine with no key and no network. The metric that matters is recall on
high items: a false negative is a person in danger who is silently downgraded. Precision matters
too, but a false positive costs a clinician one glance, not a life.

**The full pipeline** (`--llm`) additionally sends each item to the model, so it measures the
thing the floor alone cannot: whether `final_risk` ever lands *below* what the corpus expects.
Under-classification is the only failure mode the guardrails cannot forgive, so it is reported
first and separately from exact agreement. Moderate items are expected to be missed by the
keyword screen — that is by design, the model is what grades them.

Every corpus item is invented. See `scripts/safety_corpus.json`.
"""

import argparse
import asyncio
import json
import os
import sys
import time
from collections import Counter
from dataclasses import dataclass, field
from datetime import UTC, datetime
from pathlib import Path

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))

from app.services.analysis.keywords import screen

CORPUS = Path(__file__).resolve().parent / "safety_corpus.json"
LEVELS = ("low", "moderate", "high")


@dataclass
class Item:
    text: str
    expected: str
    note: str


@dataclass
class Result:
    item: Item
    predicted: str
    detail: dict[str, str] = field(default_factory=dict)

    @property
    def correct(self) -> bool:
        return self.predicted == self.item.expected

    @property
    def under_classified(self) -> bool:
        order = {level: index for index, level in enumerate(LEVELS)}
        return order[self.predicted] < order[self.item.expected]


def load_corpus() -> list[Item]:
    raw = json.loads(CORPUS.read_text(encoding="utf-8"))
    return [Item(row["text"], row["expected"], row.get("note", "")) for row in raw]


def evaluate_screen(items: list[Item]) -> list[Result]:
    """The floor in isolation: fires, or stays silent (which is 'not high')."""
    return [Result(item, "high" if screen(item.text) else "not_high") for item in items]


async def evaluate_pipeline(items: list[Item]) -> list[Result]:
    from app.services.analysis.pipeline import analyze_checkin

    results: list[Result] = []
    for item in items:
        started = time.monotonic()
        outcome = await analyze_checkin(item.text)
        results.append(
            Result(
                item,
                outcome.final_risk,
                {
                    "risk_source": outcome.risk_source,
                    "ms": f"{(time.monotonic() - started) * 1000:.0f}",
                },
            )
        )
    return results


def confusion(items: list[Item], results: list[Result]) -> dict[str, int]:
    """High-risk detection stats: the floor either fires or it does not."""
    truth_high = {id(r.item) for r in results if r.item.expected == "high"}
    predicted_high = {id(r.item) for r in results if r.predicted == "high"}
    tp = len(truth_high & predicted_high)
    fn = len(truth_high - predicted_high)
    fp = len(predicted_high - truth_high)
    tn = len(items) - tp - fn - fp
    return {
        "true_positive": tp,
        "false_negative": fn,
        "true_negative": tn,
        "false_positive": fp,
        "recall": tp / (tp + fn) if tp + fn else 1.0,
        "precision": tp / (tp + fp) if tp + fp else 1.0,
    }


def _pct(value: float) -> str:
    return f"{value:.0%}"


def report(screen_results: list[Result], pipeline_results: list[Result] | None) -> str:
    items = [r.item for r in screen_results]
    stats = confusion(items, screen_results)
    expected_counts = Counter(i.expected for i in items)
    lines: list[str] = []

    high_total = stats["true_positive"] + stats["false_negative"]
    lines.append("# Safety evaluation results")
    lines.append("")
    lines.append(
        f"Generated by `scripts/eval_safety.py` on "
        f"{datetime.now(UTC).strftime('%Y-%m-%d %H:%M UTC')} "
        f"({'floor + live pipeline' if pipeline_results else 'floor only, offline'})."
    )
    lines.append("")
    lines.append(
        f"Corpus: **{len(items)} synthetic check-ins** ({expected_counts['high']} high, "
        f"{expected_counts['moderate']} moderate, {expected_counts['low']} low), all invented"
        " — see `scripts/safety_corpus.json`. No real patient text was used."
    )
    lines.append("")
    lines.append(
        "Reproduce the first table offline with `uv run python scripts/eval_safety.py` (no key, "
        "deterministic). Both tables come from "
        "`COMMANDCODE_API_KEY=… uv run python scripts/eval_safety.py --llm "
        "--write docs/eval-results.md`, which makes one live call per item."
    )
    lines.append("")

    lines.append("## Keyword floor alone (offline, deterministic)")
    lines.append("")
    lines.append(
        "The floor only ever says *high* or nothing, so it is scored as a high-risk detector. "
        "A miss here is not a final miss — the model still grades the item — but it is how much "
        "of the safety net depends on a model behaving well."
    )
    lines.append("")
    lines.append("| Metric | Value |")
    lines.append("| --- | --- |")
    lines.append(
        f"| Recall on high-risk items | **{_pct(stats['recall'])}** "
        f"({stats['true_positive']}/{high_total}) |"
    )
    lines.append(
        f"| Precision of the floor | {_pct(stats['precision'])} "
        f"({stats['true_positive']} true / {stats['false_positive']} false) |"
    )
    lines.append(f"| Missed high-risk items | {stats['false_negative']} |")
    lines.append(f"| False alarms | {stats['false_positive']} |")
    lines.append("")

    if pipeline_results:
        under = [r for r in pipeline_results if r.under_classified]
        exact = [r for r in pipeline_results if r.correct]
        over = len(pipeline_results) - len(exact) - len(under)
        by_expected: dict[str, Counter] = {}
        for r in pipeline_results:
            by_expected.setdefault(r.item.expected, Counter())[r.predicted] += 1

        lines.append("## Full pipeline: floor + model + guardrails (`final_risk`)")
        lines.append("")
        lines.append(
            f"- Exact agreement: **{len(exact)}/{len(pipeline_results)}** "
            f"({_pct(len(exact) / len(pipeline_results))})"
        )
        lines.append(
            f"- **Under-classified (predicted below expected): {len(under)}** — the only "
            "failure direction the guardrails cannot forgive"
        )
        lines.append(f"- Over-classified (the safe direction): {over}")
        lines.append("")
        lines.append("| Expected \\ predicted | " + " | ".join(LEVELS) + " |")
        lines.append("| --- | " + " | ".join("---" for _ in LEVELS) + " |")
        for level in LEVELS:
            row = by_expected.get(level, Counter())
            cells = " | ".join(str(row.get(lvl, 0)) for lvl in LEVELS)
            lines.append(f"| {level} | {cells} |")
        lines.append("")

    source = pipeline_results or screen_results
    misses = [r for r in screen_results if r.item.expected == "high" and r.predicted != "high"]
    if misses:
        lines.append("### High-risk items the floor on its own does not catch")
        lines.append("")
        for r in misses:
            lines.append(f'- "{r.item.text}"  \n  _{r.item.note}_')
        lines.append("")
        if pipeline_results:
            lines.append(
                "None of these survived to the final result: every high item in the corpus was "
                "still reported as `high` by the full pipeline, either by the model or by the "
                "guardrail that re-screens the model's own quote."
            )
            lines.append("")

    false_alarms = [r for r in source if r.predicted == "high" and r.item.expected != "high"]
    if false_alarms:
        lines.append("### Items flagged where the corpus expects otherwise")
        lines.append("")
        for r in false_alarms:
            lines.append(f'- "{r.item.text}"  \n  _expected {r.item.expected} — {r.item.note}_')
        lines.append("")
        lines.append(
            "Deliberate: the floor errs toward paging a clinician. Missing a real crisis costs "
            "more than one extra glance at an inbox."
        )
        lines.append("")

    if pipeline_results:
        times = sorted(int(r.detail["ms"]) for r in pipeline_results if r.detail.get("ms"))
        if times:
            lines.append(
                f"Latency per check-in: median {times[len(times) // 2]} ms, max {max(times)} ms "
                f"over {len(times)} calls. The patient waits about this long after submit — the "
                "check-in is already stored by then, so a slow model is annoying, not dangerous."
            )
            lines.append("")

    lines.append("## What these numbers do not cover")
    lines.append("")
    lines.append(
        "- **One model, one language, one day.** Everything above is "
        "`deepseek/deepseek-v4-flash` on English. Change the model id and the moderate/low "
        "boundary moves; the high boundary is protected by the floor, not by the model."
    )
    lines.append(
        "- **A corpus written by the same person as the rules.** Broad enough to be useful, "
        "small enough to overfit. Real check-ins are longer, ungrammatical, and code-switched."
    )
    lines.append(
        "- **Nothing about transcription.** A clip that transcribes badly changes what the floor "
        "can see at all; that has to be measured with real audio."
    )
    if pipeline_results:
        under = [r for r in pipeline_results if r.under_classified]
        if under:
            listed = "; ".join(f'"{r.item.text[:48]}" → {r.predicted}' for r in under)
            lines.append(
                f"- **{len(under)} under-classification(s) in this run** ({listed}). All are "
                "moderate→low: no high item was ever reported below high. These read as "
                "labelling judgement as much as model error."
            )
        else:
            lines.append("- **No under-classification in this run.**")
        lines.append(
            "- **Run to run this moves.** Temperature is 0.1, not 0: repeated runs on the same "
            "corpus have differed by one or two moderate/low judgements. The high row has been "
            "19/19 on every run so far, which is the invariant worth watching."
        )
    lines.append(
        "- **Alerting, not detection.** This measures the risk label. Whether a clinician "
        "actually sees it in time is a workflow question this corpus says nothing about."
    )
    lines.append("")
    return "\n".join(lines)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Evaluate the safety pipeline")
    parser.add_argument("--llm", action="store_true", help="also run the full pipeline (network)")
    parser.add_argument("--write", metavar="PATH", help="write the markdown report to PATH")
    args = parser.parse_args(argv)

    if args.llm and not os.getenv("COMMANDCODE_API_KEY"):
        print("--llm needs COMMANDCODE_API_KEY", file=sys.stderr)
        return 2

    items = load_corpus()
    screen_results = evaluate_screen(items)
    # The only awaitable work, and it is fine to block here: this is a CLI, not a server.
    pipeline_results = asyncio.run(evaluate_pipeline(items)) if args.llm else None
    text = report(screen_results, pipeline_results)
    print(text)

    if args.write:
        Path(args.write).write_text(text + "\n", encoding="utf-8")
        print(f"\n[written to {args.write}]", file=sys.stderr)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
